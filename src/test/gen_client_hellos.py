#!/usr/bin/env python3
"""
Generates client_hellos.h: real TLS ClientHello records used by test_tls_split.c

The hellos are produced by the local OpenSSL through Python's ssl module (no network involved).
With OpenSSL >= 3.5 the TLS 1.3 hello carries a post-quantum (X25519MLKEM768) key share, which
makes it larger than a typical TCP segment, i.e. the hello gets split across segments.

For each hello we emit two extension orders:
  - sni_first: SNI is the first extension (BoringSSL/Conscrypt default order, used by most Android apps)
  - sni_last:  SNI is the last extension (worst case, also possible with Chrome's extension permutation)

Usage: python3 -I gen_client_hellos.py > client_hellos.h
"""
import ssl
import sys

SNI_EXTENSION = 0x0000


def client_hello(server_name, tls12_only=False):
    ctx = ssl.SSLContext(ssl.PROTOCOL_TLS_CLIENT)
    ctx.check_hostname = False
    ctx.verify_mode = ssl.CERT_NONE
    ctx.set_alpn_protocols(["h2", "http/1.1"])
    if tls12_only:
        ctx.maximum_version = ssl.TLSVersion.TLSv1_2
    incoming, outgoing = ssl.MemoryBIO(), ssl.MemoryBIO()
    sock = ctx.wrap_bio(incoming, outgoing, server_hostname=server_name)
    try:
        sock.do_handshake()
    except ssl.SSLWantReadError:
        pass
    return outgoing.read()


def extensions_offset(hello):
    pos = 5 + 4 + 2 + 32  # record header, handshake header, version, random
    pos += 1 + hello[pos]  # session id
    pos += 2 + int.from_bytes(hello[pos:pos + 2], "big")  # cipher suites
    pos += 1 + hello[pos]  # compression methods
    return pos


def reorder_extensions(hello, sni_first):
    pos = extensions_offset(hello)
    ext_len = int.from_bytes(hello[pos:pos + 2], "big")
    start, end = pos + 2, pos + 2 + ext_len
    assert end == len(hello), "expected a single record containing only the ClientHello"

    extensions = []
    pos = start
    while pos < end:
        ext_type = int.from_bytes(hello[pos:pos + 2], "big")
        length = int.from_bytes(hello[pos + 2:pos + 4], "big")
        extensions.append((ext_type, hello[pos:pos + 4 + length]))
        pos += 4 + length

    sni = [raw for ext_type, raw in extensions if ext_type == SNI_EXTENSION]
    others = [raw for ext_type, raw in extensions if ext_type != SNI_EXTENSION]
    assert len(sni) == 1
    ordered = sni + others if sni_first else others + sni
    # Same extensions, same total length: record and handshake lengths stay valid
    return hello[:start] + b"".join(ordered)


def emit(name, server_name, data):
    print(f"// {len(data)} bytes, SNI {server_name}")
    print(f"static const unsigned char {name}[] = {{")
    for i in range(0, len(data), 16):
        print("        " + ", ".join(f"0x{b:02x}" for b in data[i:i + 16]) + ",")
    print("};")
    print()


def main():
    hellos = [
        ("tls13_pq", "app-measurement.com", False),
        ("tls13_pq_long_sni", "a" * 63 + "." + "b" * 63 + "." + "c" * 63 + ".tracker.example.com", False),
        ("tls12", "app-measurement.com", True),
    ]

    print(f"// Generated by gen_client_hellos.py with {ssl.OPENSSL_VERSION}. Do not edit.")
    print("#ifndef CLIENT_HELLOS_H")
    print("#define CLIENT_HELLOS_H")
    print()
    entries = []
    for name, server_name, tls12_only in hellos:
        hello = client_hello(server_name, tls12_only)
        for order in ("sni_first", "sni_last"):
            variant = f"{name}_{order}"
            emit(variant, server_name, reorder_extensions(hello, order == "sni_first"))
            entries.append((variant, server_name))

    print("struct client_hello {")
    print("    const char *name;")
    print("    const char *server_name;")
    print("    const unsigned char *data;")
    print("    size_t len;")
    print("};")
    print()
    print("static const struct client_hello client_hellos[] = {")
    for variant, server_name in entries:
        print(f'        {{"{variant}", "{server_name}", {variant}, sizeof({variant})}},')
    print("};")
    print()
    print("#endif // CLIENT_HELLOS_H")


if __name__ == "__main__":
    sys.exit(main())
